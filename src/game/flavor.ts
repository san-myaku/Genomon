/**
 * 候補を集める。
 *
 * 【エクスポートしている理由】
 *   分布を実測する道具（`tools/cardStats.ts`）と、
 *   「どの個体にも十分な候補があるか」を見るテストから使う。
 *   候補が痩せている条件があると、そこだけ「またこの文だ」が起きる。
 */
export function flavorCandidateCount(pheno: Phenotype): { specific: number; total: number } {
  const all = collect(pheno);
  return { specific: all.length - GENERIC.length, total: all.length };
}

function collect(pheno: Phenotype): Candidate[] {
  const out: Candidate[] = [...GENERIC];
  addPattern(out, pheno);
  out.push(...(PALETTE[pheno.palette.family] ?? []));
  addTexture(out, pheno);
  addOrgans(out, pheno);
  addLight(out, pheno);
  addNumeric(out, pheno);
  addPersonality(out, pheno);
  return out;
}

/**
 * この個体のフレーバー 1 本。
 *
 * 【呼ぶ順番を変えないこと】
 *   `rng` の消費順がそのまま結果を決める。条件の追加は `collect()` の中
 *   （候補の中身）で行い、ここの `bool` → `pick` → `bool` → `pick` の
 *   並びは変えない。並べ替えると、既存個体の文が総入れ替えになる。
 */
export function deriveFlavorText(pheno: Phenotype): FlavorText {
  const candidates = collect(pheno);
  const rng = new Rng(pheno.seed).stream('card:flavor');

  const specific = candidates.slice(GENERIC.length);
  const opening =
    specific.length > 0 && rng.bool(0.72) ? rng.pick(specific) : rng.pick(candidates);

  const closers = CLOSERS[opening.follow];
  if (closers.length === 0) return { kind: opening.kind, text: opening.text };

  // 続きを付けるかどうかは先に決める（付けない場合も pick を 1 回消費して
  // おくと、候補数を増やしたときに既存個体の文が動く。ここでは消費しない）。
  if (!rng.bool(0.58)) return { kind: opening.kind, text: opening.text };

  const closer = rng.pick(closers);
  const joined = opening.text + closer;
  // カード表面は 2 行しか無い。あふれる組み合わせは 1 文で返す。
  return { kind: opening.kind, text: joined.length <= MAX_LEN ? joined : opening.text };
}
