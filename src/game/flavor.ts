/**
 * 個体固有のフレーバーテキスト。
 *
 * 数値説明ではなく「この個体の外側にも世界が続いている」と感じさせる
 * 短い観察記録。AI にその場で作文させず、人が書いた文の集合から
 * Phenotype と seed に応じて決定論的に選ぶ。
 *
 * 【書きかたの約束】
 *   避けるもの: 「このゲノモンは非常に珍しく、強い力を秘めている」のような、
 *   抽象的で何も言っていない文。優先するもの: 具体的な行動・観察記録・
 *   育種家の経験・古い記録・伝承・系統の逸話。
 *
 * 【鑑定前に断定してはいけないこと】
 *   保因している形質を名指ししない。「かもしれない」「まだ分からない」の
 *   側に立った匂わせまでは書いてよい（鑑定後に読み返すと意味が増す）。
 *   材料に使ってよいのは **姿に出ているもの**（`parts` は実際に描かれた
 *   対立遺伝子）と、画面に出ている数値・性格まで。`genotype` は見ない。
 *
 * ─────────────────────────────────────────────────────────
 * 【文の数について — 二度、実測して作り直した】
 *
 *   第 1 版: 600 個体で 39 種類。最頻の 1 文が 11%。
 *     原因は条件別の候補が 1〜2 本しか無かったこと。
 *   第 2 版: 候補を厚くして 126 種類・最頻 3.2% まで改善。
 *     しかし **カードを数百枚集める** 前提では、まだ「またこの文だ」が来る。
 *
 *   第 3 版（この版）は、固定文をただ足すのではなく **組み立てかた** を変えた。
 *
 *     1 文の観察（openings）＋ 続きの一言（closers）
 *
 *   closers は「どんな観察のあとに置いても続きとして読める」ように
 *   **続き専用に書き下ろした** 短文で、系統（FIELD NOTE / ARCHIVE / …）ごとに
 *   別のプールを持つ。opening が N 本・その系統の closer が M 本あれば、
 *   組み合わせは N×(M+1) 通りになる。機械的な穴埋め（「○○な個体は、
 *   △△することがある」）とは違い、**両方とも人が書いた文** なので
 *   品質が落ちない。
 *
 *   ことわざ（OLD SAYING）だけは続きを付けない。格言は一文で閉じる形が
 *   正しく、後ろに観察記録を足すと格言に見えなくなる。
 *
 *   長さの上限（`MAX_LEN`）を持たせているのは、カード表面のフレーバー欄が
 *   2 行しか無いため。あふれる組み合わせは closer を付けずに 1 文で返す。
 *
 *   分布は `tests/grading.test.ts` と `tools/cardStats.ts` が実測している。
 * ─────────────────────────────────────────────────────────
 */

