/**
 * 個体固有のフレーバーテキスト。
 *
 * 数値説明ではなく「この個体の外側にも世界が続いている」と感じさせる
 * 短い観察記録。AI にその場で作文させず、人が書いた文の集合から
 * Phenotype と seed に応じて決定論的に選ぶ。
 *
 * 【書きかたの約束】
 *   避けるもの: 「このゲノモンは非常に珍しく、強い力を秘めている」のような、
 *   抽象的で何も言っていない文。優先するもの: 具体的な行動・観察記録・
 *   育種家の経験・古い記録・伝承・系統の逸話。
 *
 * 【鑑定前に断定してはいけないこと】
 *   保因している形質を名指ししない。「かもしれない」「まだ分からない」の
 *   側に立った匂わせまでは書いてよい（鑑定後に読み返すと意味が増す）。
 *
 * 【文の数について — 実測して増やした】
 *   最初の版は 600 個体で 39 種類しか出ず、最頻の 1 文が 11% を占め、
 *   半数の個体が 11 種類に集中していた。原因は条件別の候補が
 *   1〜2 本しか無かったこと（「毛がある」だけで 36% の個体が同じ文になる）。
 *   条件を増やすより、**各条件の候補を厚くする**ほうが効く。
 *   `tests/grading.test.ts` が集中度を機械的に見ている。
 */

import type { Phenotype } from '../core/types.ts';
import { Rng } from '../core/rng.ts';

export type FlavorKind = 'FIELD NOTE' | 'BREEDER NOTE' | 'ARCHIVE' | 'OLD SAYING';

export interface FlavorText {
  kind: FlavorKind;
  text: string;
}

