function addPattern(out: Candidate[], p: Phenotype): void {
  for (const entry of PATTERN) {
    if (entry.match.test(p.parts.pattern)) {
      out.push(...entry.lines);
      return;
    }
  }
}

function addPalette(out: Candidate[], p: Phenotype): void {
  out.push(...(PALETTE[p.palette.family] ?? []));
}

function addTexture(out: Candidate[], p: Phenotype): void {
  out.push(...(TEXTURE[p.parts.texture] ?? []));
}

function addBody(out: Candidate[], p: Phenotype): void {
  out.push(...(COAT[p.parts.coat] ?? []));

  if (p.parts.lumin !== 'none' || p.glow > 0.62) out.push(...LUMIN);

  if (p.translucency > 0.58) {
    out.push(
      F('向こう側が透けて見えるのに、影だけは妙にはっきりしている。'),
      A('透けている個体の記録は、必ず背景ごと描かれている。'),
    );
  }
  if (p.size > 1.12) {
    out.push(
      B('大きさは記録しやすい。大きくなった理由は、いつも記録しにくい。'),
      F('入口をくぐるとき、一度だけ止まって幅を確かめる。'),
    );
  } else if (p.size < 0.9) {
    out.push(
      A('小さい個体ほど余白を広く取れ、と古い標本規格にある。'),
      F('手のひらに乗せると、体温より先に重さに驚く。'),
    );
  }
  if (p.asymmetry > 0.62) {
    out.push(
      F('左右で少し違う。どちらが「正しい」かは書かれていない。'),
      B('揃っていないことを欠点と書くな。揃いすぎる系統の方が脆い。'),
    );
  }
}

