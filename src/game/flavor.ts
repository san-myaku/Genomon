/**
 * カードと詳細画面に刷る見出し。
 *
 * 内部の分類（どの条件から出た文か）はもっと細かいが、画面に出す label は
 * 6 種類に抑える。増やすと見出しの方が目立ち、文が読まれなくなる。
 */
export type FlavorKind =
  | 'FIELD NOTE'
  | 'BREEDER NOTE'
  | 'KEEPER NOTE'
  | 'LINEAGE NOTE'
  | 'ARCHIVE'
  | 'OLD SAYING';

export interface FlavorText {
  kind: FlavorKind;
  text: string;
}

/**
 * 続きの一言をどのプールから選ぶか。'none' は続きを付けない。
 *
 * 【'advice' と 'breeding' を分けている理由 — 実際に噛み合わなかった】
 *   育種家の言葉には「教え」（迷ったら両方残せ）と「顛末」（三代あとに
 *   基準になった）の二種類がある。両方に同じ続きを付けると、
 *   「迷ったら両方残せ。結果が出たのは、四代あとだった。」のように
 *   **助言の主語が消える**。教えには教えの続き（そう教わったが…）を、
 *   顛末には顛末の続き（結果が出たのは…）を当てる。
 */
type Follow = 'observation' | 'record' | 'breeding' | 'advice' | 'care' | 'lineage' | 'none';

interface Candidate {
  kind: FlavorKind;
  text: string;
  follow: Follow;
}

