function addPattern(out: Candidate[], p: Phenotype): void {
  for (const entry of PATTERN) {
    if (entry.match.test(p.parts.pattern)) {
      out.push(...entry.lines);
      return;
    }
  }
}

/**
 * 姿に出ている器官から材料を足す。
 *
 * `parts` は **実際に描かれた** 対立遺伝子なので、ここを見るかぎり
 * 「画面に無いものを語る」事故が起きない（`traits` を見ると、
 * スライムの羽・耳の無い個体の耳先色まで拾ってしまう）。
 * coExpress の合成 ID（`a+b`）は素の ID と一致しないので、
 * 合成のときは両側を引く。
 */
function addFrom(out: Candidate[], table: Readonly<Record<string, readonly Candidate[]>>, id: string): void {
  if (!id || id === 'none') return;
  for (const part of id.split('+')) {
    out.push(...(table[part] ?? []));
  }
}

function addOrgans(out: Candidate[], p: Phenotype): void {
  const q = p.parts;
  addFrom(out, HORNS, q.horns);
  addFrom(out, ANTENNAE, q.antennae);
  addFrom(out, WINGS, q.wings);
  addFrom(out, TAIL, q.tail);
  addFrom(out, PLANT, q.plant);
  addFrom(out, COLLAR, q.collar);
  addFrom(out, FEET, q.feet);
  addFrom(out, FLOATERS, q.floaters);
  addFrom(out, EARS, q.ears);
  addFrom(out, EYE_SHAPE, q.eyeShape);
  addFrom(out, PUPIL, q.pupil);
  addFrom(out, MOUTH, q.mouth);
  addFrom(out, BICOLOR, q.bicolor);
  addFrom(out, SILHOUETTE, q.silhouette);

  if (q.eyeCount === 1) {
    out.push(
      F('一つの目が、こちらの右手だけを追う日がある。'),
      A('目の数の欄は、この個体のために作られた。'),
      S('目が一つの子を憐れむな。見ている物の数は同じだ。'),
    );
  } else if (q.eyeCount >= 3) {
    out.push(
      F('三つの目のうち、真ん中だけが遅れて閉じる。'),
      A('どの目を基準に間隔を測るか、記録係ごとに違っている。'),
      B('目の数は狙って出せない。出た年は兄弟ごと残せ。'),
    );
  }
}

function addTexture(out: Candidate[], p: Phenotype): void {
  out.push(...(TEXTURE[p.parts.texture] ?? []));
  out.push(...(COAT[p.parts.coat] ?? []));
}

function addLight(out: Candidate[], p: Phenotype): void {
  addFrom(out, LUMIN, p.parts.lumin);
  if (p.parts.lumin !== 'none' || p.glow > 0.62) out.push(...GLOW_ANY);
}

