export type IconName = keyof typeof PATHS;

export interface IconOpts {
  /** 文字サイズに対する倍率。既定 1（＝1em 相当）。 */
  scale?: number;
  /** 読み上げさせたい名前。省略時は装飾扱い（aria-hidden）。 */
  label?: string;
  /** 追加のクラス。 */
  cls?: string;
}

/**
 * アイコン 1 個を `<svg>` 文字列で返す。
 *
 * **戻り値は HTML なので `esc()` に通さないこと。** 引数はすべて型か数値なので、
 * 外部入力がそのまま混ざる経路はない。
 */
export function icon(name: IconName, o: IconOpts = {}): string {
  const em = o.scale && Number.isFinite(o.scale) ? Math.max(0.4, Math.min(4, o.scale)) : 1;
  const a11y = o.label
    ? `role="img" aria-label="${o.label.replace(/[&<>"]/g, '')}"`
    : 'aria-hidden="true"';
  return (
    `<svg class="ico${o.cls ? ` ${o.cls}` : ''}" viewBox="0 0 24 24" ${a11y} focusable="false"` +
    ` width="${em * BOX}em" height="${em * BOX}em" fill="none" stroke="currentColor"` +
    ` stroke-width="${STROKE}" stroke-linecap="round" stroke-linejoin="round">${PATHS[name]}</svg>`
  );
}

/**
 * 1em に対する実際の枠の大きさ。
 *
 * 【1.0 ではなく 1.26 にした理由】
 *   置き換え後の画面を撮って並べたら、線画が絵文字より一回り小さく見えた。
 *   絵文字は字送りいっぱいまで絵が詰まっているのに対し、この 24×24 の枠は
 *   中身が y=3.4〜20.6 のあたり＝**枠の約 72%** しか埋めていない。
 *   同じ font-size で置き換えると、その差がそのまま「小さくなった」に見える。
 *   1/0.72 ≒ 1.39 は行けすぎるので、隣の文字と釣り合う 1.26 に落とした。
 *   （呼び出し側の font-size 指定は既存のまま使えるようにするための調整で、
 *     各所の CSS を書き換えて回るより 1 か所で済む。）
 */
const BOX = 1.26;

/**
 * 線の太さ。
 *
 * ラベルの日本語が font-weight 700〜800 なので、1.9 だと線画だけ痩せて見えた。
 * 生きもの本体の輪郭（strokeW 2.7〜3.35 / viewBox 200 相当）とも釣り合う値にする。
 */
const STROKE = 2.1;

/** 名前が実在するか（設定ファイル由来の文字列を検証するとき用）。 */
export function isIconName(v: string): v is IconName {
  return Object.prototype.hasOwnProperty.call(PATHS, v);
}

/**
 * 「アイコン名なら線画、そうでなければ文字のまま」を返す。
 *
 * 絵文字から線画への移し替えを **1 ファイルずつ** 進めるための足場。
 * 見出し・ゲージ・世話ボタンなど、アイコンを受け取る口はすべて共通の
 * ヘルパを通っているので、そこを一斉に `IconName` へ変えると
 * 型検査が広範囲で赤くなり、途中の状態でアプリが動かなくなる。
 * ここで受け皿を広げておけば、各所を順に置き換えても常に動く。
 *
 * **移し替えが終わったら、この関数と文字列側の分岐は消すこと。**
 * 残したままだと、綴りを間違えたアイコン名が黙って文字として表示され、
 * 型検査が拾えなくなる。
 */
export function iconOrText(v: string, o: IconOpts = {}): string {
  if (isIconName(v)) return icon(v, o);
  return v.replace(/[&<>"]/g, (c) => `&#${c.charCodeAt(0)};`);
}
